import { readFileSync, writeFileSync } from "node:fs";
const file = process.argv[2];
if (!file || !/src\/storage\/migrations\/\d+_development_plans_rls\.sql$/.test(file)) throw new Error("Pass the empty Drizzle development_plans_rls migration");
if (readFileSync(file, "utf8").trim() !== "-- Custom SQL migration file, put you code below! --") throw new Error("Refusing to overwrite an existing migration");
const statements = [];
for (const table of ["competency_development_plans", "competency_plan_activities", "competency_plan_history"]) {
 const scope = `"tenant_id" = current_setting('app.tenant_id', true)::uuid`;
 statements.push(`ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY;`, `CREATE POLICY "${table}_read" ON "${table}" FOR SELECT USING (${scope});`, `CREATE POLICY "${table}_append" ON "${table}" FOR INSERT WITH CHECK (${scope});`);
 if (table !== "competency_plan_history") statements.push(`CREATE POLICY "${table}_update" ON "${table}" FOR UPDATE USING (${scope}) WITH CHECK (${scope});`);
}
writeFileSync(file, "-- Generated by generate-development-plans-rls.mjs\n" + statements.join("\n--> statement-breakpoint\n") + "\n");
