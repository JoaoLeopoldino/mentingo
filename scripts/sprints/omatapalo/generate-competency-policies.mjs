// Generate non-generatable RLS SQL into an empty Drizzle --custom migration.
// Never execute SQL or connect to a database here.
import { readFileSync, writeFileSync } from 'node:fs';
const file = process.argv[2];
if (!file || !/src\/storage\/migrations\/\d+_competency_tenant_policies\.sql$/.test(file)) throw new Error('Pass the empty competency_tenant_policies Drizzle migration');
const original = readFileSync(file, 'utf8');
if (original.trim() !== '-- Custom SQL migration file, put you code below! --') throw new Error('Refusing to overwrite an existing migration');
const tables=['competencies','competency_levels','competency_job_roles','competency_requirements','competency_assignments','competency_evidence'];
const statements=[];
for (const table of tables) {
 statements.push(`ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY;`);
 const expression=`"tenant_id" = current_setting('app.tenant_id', true)::uuid`;
 if(table==='competency_evidence') {
  statements.push(`CREATE POLICY "${table}_read" ON "${table}" FOR SELECT USING (${expression});`);
  statements.push(`CREATE POLICY "${table}_append" ON "${table}" FOR INSERT WITH CHECK (${expression});`);
 } else statements.push(`CREATE POLICY "${table}_tenant_isolation" ON "${table}" USING (${expression}) WITH CHECK (${expression});`);
}
writeFileSync(file, '-- Generated by scripts/sprints/omatapalo/generate-competency-policies.mjs\n'+statements.join('\n--> statement-breakpoint\n')+'\n');
