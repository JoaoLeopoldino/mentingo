import { readFileSync, writeFileSync } from "node:fs";
const file = process.argv[2];
if (!file || !/src\/storage\/migrations\/\d+_competency_decisions_backfill\.sql$/.test(file))
  throw new Error("Pass the empty Drizzle competency_decisions_backfill migration");
if (readFileSync(file, "utf8").trim() !== "-- Custom SQL migration file, put you code below! --")
  throw new Error("Refusing to overwrite an existing migration");
const statements = [];
for (const table of [
  "competency_evidence_reviews",
  "competency_assessments",
  "competency_revocations",
]) {
  const isolation = `"tenant_id" = current_setting('app.tenant_id', true)::uuid`;
  statements.push(
    `ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY;`,
    `CREATE POLICY "${table}_read" ON "${table}" FOR SELECT USING (${isolation});`,
    `CREATE POLICY "${table}_append" ON "${table}" FOR INSERT WITH CHECK (${isolation});`,
  );
}
// Only legacy approvals become formal assessments. Rejected/pending evidence is retained verbatim.
// Stable IDs and preserved chronology retain traceability; new submissions cannot request legacy type.
statements.push(`INSERT INTO competency_assessments (id, tenant_id, user_id, competency_id, level, revision, source_evidence_id, supersedes_assessment_id, rationale, assessor_id, assessed_at, expires_at, review_at, command_hash, created_at, updated_at)
SELECT id, tenant_id, user_id, competency_id, level,
 row_number() OVER (PARTITION BY tenant_id, user_id, competency_id ORDER BY created_at, id)::integer,
 id, lag(id) OVER (PARTITION BY tenant_id, user_id, competency_id ORDER BY created_at, id),
 evidence, COALESCE(assessor_id, recorded_by), COALESCE(assessed_at, created_at), expires_at, review_at,
 md5('legacy:' || id::text), created_at, updated_at
FROM competency_evidence WHERE status = 'approved' AND evidence_type = 'legacy'
ON CONFLICT (id) DO NOTHING;`);
writeFileSync(
  file,
  "-- Generated by generate-competency-decision-backfill.mjs; no source evidence is changed.\n" +
    statements.join("\n--> statement-breakpoint\n") +
    "\n",
);
